// Get current language
function getCurrentLanguage() {
    return localStorage.getItem('bossjob_language') || 'en';
}

// Set language
function setLanguage(lang) {
    localStorage.setItem('bossjob_language', lang);
    applyTranslations(lang);
    updateLanguageSelector(lang);
}

// Apply translations to page
function applyTranslations(lang) {
    const elements = document.querySelectorAll('[data-translate]');
    
    elements.forEach(element => {
        const key = element.getAttribute('data-translate');
        const translation = translations[lang]?.[key] || translations.en[key] || key;
        
        if (element.tagName === 'INPUT' && element.type === 'text') {
            element.placeholder = translation;
        } else if (element.tagName === 'INPUT' && element.type === 'submit') {
            element.value = translation;
        } else {
            element.textContent = translation;
        }
    });
    
    // Update document title
    const titleElement = document.querySelector('title');
    if (titleElement) {
        const pageTitle = titleElement.getAttribute('data-translate-title');
        if (pageTitle) {
            titleElement.textContent = translations[lang]?.[pageTitle] || translations.en[pageTitle] || pageTitle;
        }
    }
    
    // Update html lang attribute
    document.documentElement.lang = lang;
}

// Update language selector UI
function updateLanguageSelector(lang) {
    document.querySelectorAll('.language-selector select').forEach(select => {
        select.value = lang;
    });
}

// Create language selector component
function createLanguageSelector() {
    const selectors = document.querySelectorAll('.language-selector');
    
    selectors.forEach(selector => {
        if (selector.querySelector('select')) return;
        
        const select = document.createElement('select');
        select.innerHTML = `
            <option value="en">EN</option>
            <option value="am">አማ</option>
            <option value="om">Oro</option>
        `;
        select.value = getCurrentLanguage();
        select.addEventListener('change', (e) => {
            setLanguage(e.target.value);
        });
        
        selector.appendChild(select);
    });
}

// Initialize language system
document.addEventListener('DOMContentLoaded', () => {
    const currentLang = getCurrentLanguage();
    createLanguageSelector();
    applyTranslations(currentLang);
    updateLanguageSelector(currentLang);
});

// Export functions
window.setLanguage = setLanguage;
window.getCurrentLanguage = getCurrentLanguage;
window.applyTranslations = applyTranslations;
